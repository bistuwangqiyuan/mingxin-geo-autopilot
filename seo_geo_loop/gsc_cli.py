"""GSC CLI — durable, browser-free Google Search Console automation for mingxinstorage.xyz.

Pure standard library (no pip installs). Uses Google OAuth 2.0 "installed app"
(loopback) flow once, caches a refresh token locally, then calls the Search
Console REST API headlessly thereafter.

What this DOES cover (official API, durable):
  - sites        : list verified properties on the account
  - sitemaps     : list submitted sitemaps for a property
  - submit-sitemap : (PUT) submit / resubmit a sitemap feed
  - inspect      : URL Inspection (read-only index status of a page)
  - inspect-batch: inspect many URLs (from sitemap or a file) -> JSON report
  - analytics    : Search Analytics query (clicks / impressions / position / queries)

What this does NOT cover (Google restriction, not ours):
  - "Request Indexing" (请求编入索引) has NO public API. Google's Indexing API
    only supports JobPosting / BroadcastEvent pages, not general web pages.
    That daily action must be done in the browser (see README / browser session).

Security:
  - We never store your Google password. OAuth stores only a refresh token.
  - Client secret + token live under seo_geo_loop/secrets/ which is gitignored.

Setup (one-time, ~3 min): see `python gsc_cli.py setup-help`.
"""
