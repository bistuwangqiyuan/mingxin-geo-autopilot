def _request(method: str, url: str, *, headers: dict | None = None,
             data: bytes | None = None, timeout: int = 45) -> tuple[int, str]:
    req = urllib.request.Request(url, data=data, method=method,
                                 headers={"User-Agent": _UA, **(headers or {})})
    try:
        r = urllib.request.urlopen(req, timeout=timeout)
        return r.status, r.read().decode("utf-8", "ignore")
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode("utf-8", "ignore")
    except Exception as e:  # noqa: BLE001
        return -1, f"{type(e).__name__}: {e}"


def _post_form(url: str, form: dict, timeout: int = 45) -> tuple[int, dict]:
    body = urllib.parse.urlencode(form).encode()
    st, txt = _request("POST", url, headers={"Content-Type": "application/x-www-form-urlencoded"},
                       data=body, timeout=timeout)
    try:
        return st, json.loads(txt) if txt else {}
    except json.JSONDecodeError:
        return st, {"raw": txt}


def _api(method: str, path: str, token: str, *, payload: dict | None = None) -> tuple[int, dict]:
    data = json.dumps(payload).encode() if payload is not None else None
    headers = {"Authorization": f"Bearer {token}"}
    if data is not None:
        headers["Content-Type"] = "application/json; charset=utf-8"
    st, txt = _request(method, f"{API}{path}", headers=headers, data=data)
    try:
        return st, (json.loads(txt) if txt else {})
    except json.JSONDecodeError:
        return st, {"raw": txt}


