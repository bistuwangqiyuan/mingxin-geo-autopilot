def _site_path(site: str) -> str:
    return urllib.parse.quote(site, safe="")


def cmd_sites(_args) -> int:
    st, data = _api("GET", "/webmasters/v3/sites", _access_token())
    if st != 200:
        sys.exit(f"[!] sites failed ({st}): {data}")
    entries = data.get("siteEntry", [])
    print(f"已验证属性 ({len(entries)}):")
    for e in entries:
        print(f"  - {e.get('siteUrl')}   [{e.get('permissionLevel')}]")
    return 0


def cmd_sitemaps(args) -> int:
    st, data = _api("GET", f"/webmasters/v3/sites/{_site_path(args.site)}/sitemaps", _access_token())
    if st != 200:
        sys.exit(f"[!] sitemaps failed ({st}): {data}")
    sms = data.get("sitemap", [])
    print(f"{args.site} 已提交 sitemap ({len(sms)}):")
    for s in sms:
        cont = s.get("contents", [{}])
        n = cont[0].get("submitted") if cont else "?"
        print(f"  - {s.get('path')}  | 上次下载: {s.get('lastDownloaded','-')} | "
              f"errors: {s.get('errors','0')} warnings: {s.get('warnings','0')} | submitted: {n}")
    return 0


def cmd_submit_sitemap(args) -> int:
    feed = args.feed or SITEMAP_URL
    path = f"/webmasters/v3/sites/{_site_path(args.site)}/sitemaps/{urllib.parse.quote(feed, safe='')}"
    st, data = _api("PUT", path, _access_token())
    if st in (200, 204):
        print(f"[OK] 已提交 sitemap: {feed}  (site={args.site})")
        return 0
    sys.exit(f"[!] submit-sitemap failed ({st}): {data}")


def _inspect_one(site: str, url: str, token: str) -> dict:
    st, data = _api("POST", "/v1/urlInspection/index:inspect", token, payload={
        "inspectionUrl": url, "siteUrl": site, "languageCode": "zh-CN",
    })
    if st != 200:
        return {"url": url, "ok": False, "http": st, "error": data}
    res = (data.get("inspectionResult") or {}).get("indexStatusResult", {})
    return {
        "url": url,
        "ok": True,
        "verdict": res.get("verdict"),                 # PASS / NEUTRAL / FAIL
        "coverageState": res.get("coverageState"),     # e.g. 'Submitted and indexed'
        "robotsTxtState": res.get("robotsTxtState"),
        "indexingState": res.get("indexingState"),
        "lastCrawlTime": res.get("lastCrawlTime"),
        "pageFetchState": res.get("pageFetchState"),
        "googleCanonical": res.get("googleCanonical"),
    }


def cmd_inspect(args) -> int:
    out = _inspect_one(args.site, args.url, _access_token())
    print(json.dumps(out, ensure_ascii=False, indent=2))
    return 0 if out.get("ok") else 1


def _sitemap_urls() -> list[str]:
    st, txt = _request("GET", SITEMAP_URL)
    urls: list[str] = []
    if st == 200:
        try:
            root = ET.fromstring(txt)
            for loc in root.iter():
                if loc.tag.endswith("loc") and loc.text:
                    urls.append(loc.text.strip())
        except ET.ParseError:
            pass
    return sorted(set(urls))


def cmd_inspect_batch(args) -> int:
    if args.file:
        urls = [ln.strip() for ln in Path(args.file).read_text(encoding="utf-8").splitlines()
                if ln.strip() and not ln.startswith("#")]
    else:
        urls = _sitemap_urls()
    if args.limit:
        urls = urls[: args.limit]
    if not urls:
        sys.exit("[!] 没有可检查的 URL（sitemap 为空或文件为空）。")
    token = _access_token()
    rows, summary = [], {}
    print(f"批量检查 {len(urls)} 个 URL ...")
    for i, u in enumerate(urls, 1):
        r = _inspect_one(args.site, u, token)
        rows.append(r)
        key = r.get("coverageState") or r.get("error", {}).get("error", {}).get("status") or r.get("verdict") or "UNKNOWN"
        summary[key] = summary.get(key, 0) + 1
        print(f"  [{i}/{len(urls)}] {r.get('coverageState') or r.get('verdict') or r.get('http')}  {u}")
        time.sleep(0.4)  # gentle on quota
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / "gsc_inspect_batch.json"
    out.write_text(json.dumps({
        "site": args.site,
        "checked_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
        "count": len(rows), "summary": summary, "rows": rows,
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    print("\n汇总:", json.dumps(summary, ensure_ascii=False))
    print(f"[OK] 明细写入 {out}")
    return 0


def cmd_analytics(args) -> int:
    end = datetime.now(timezone.utc).date()
    start = end - timedelta(days=args.days)
    payload = {
        "startDate": start.isoformat(),
        "endDate": end.isoformat(),
        "dimensions": args.dimensions.split(",") if args.dimensions else ["query"],
        "rowLimit": args.limit,
    }
    st, data = _api("POST", f"/webmasters/v3/sites/{_site_path(args.site)}/searchAnalytics/query",
                    _access_token(), payload=payload)
    if st != 200:
        sys.exit(f"[!] analytics failed ({st}): {data}")
    rows = data.get("rows", [])
    print(f"{args.site}  {start}~{end}  维度={payload['dimensions']}  共 {len(rows)} 行")
    for r in rows:
        keys = " | ".join(r.get("keys", []))
        print(f"  {keys:<50}  clicks={r.get('clicks',0):<6} imp={r.get('impressions',0):<7} "
              f"ctr={r.get('ctr',0)*100:.1f}% pos={r.get('position',0):.1f}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "gsc_analytics.json").write_text(
        json.dumps({"site": args.site, "range": [start.isoformat(), end.isoformat()],
                    "payload": payload, "rows": rows}, ensure_ascii=False, indent=2), encoding="utf-8")
    return 0


PROPERTIES_FILE = OUT_DIR / "gsc_properties.json"


def _load_domains() -> list[str]:
    if not PROPERTIES_FILE.exists():
        sys.exit(f"[!] 缺少属性清单 {PROPERTIES_FILE}（应包含 domains 数组）。")
    data = json.loads(PROPERTIES_FILE.read_text(encoding="utf-8"))
    domains = data.get("domains") or []
    if not domains:
        sys.exit(f"[!] {PROPERTIES_FILE} 的 domains 为空。")
    return domains


def _is_live(domain: str) -> tuple[bool, int]:
    """Cheap liveness probe for https://<domain>/ (HEAD-ish via GET)."""
    st, _ = _request("GET", f"https://{domain}/", timeout=15)
    return (200 <= st < 400), st


def cmd_submit_sitemap_all(args) -> int:
    domains = _load_domains()
    token = _access_token()
    feed_path = args.feed_path.lstrip("/")
    rows, summary = [], {}
    print(f"对 {len(domains)} 个域名属性提交 sitemap (/{feed_path}) ...")
    for i, d in enumerate(domains, 1):
        site = f"sc-domain:{d}"
        feed = f"https://{d}/{feed_path}"
        if args.check_live:
            live, code = _is_live(d)
            if not live:
                rows.append({"domain": d, "submitted": False, "reason": f"home not live ({code})"})
                summary["skipped_not_live"] = summary.get("skipped_not_live", 0) + 1
                print(f"  [{i}/{len(domains)}] skip {d} (home {code})")
                continue
        path = f"/webmasters/v3/sites/{_site_path(site)}/sitemaps/{urllib.parse.quote(feed, safe='')}"
        st, data = _api("PUT", path, token)
        ok = st in (200, 204)
        rows.append({"domain": d, "submitted": ok, "http": st, "feed": feed,
                     "error": None if ok else data})
        key = "submitted" if ok else f"http_{st}"
        summary[key] = summary.get(key, 0) + 1
        print(f"  [{i}/{len(domains)}] {'OK ' if ok else 'ERR'} {d}  ({st})")
        time.sleep(args.sleep)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / "gsc_submit_sitemap_all.json"
    out.write_text(json.dumps({
        "feed_path": feed_path, "check_live": args.check_live,
        "ran_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
        "count": len(rows), "summary": summary, "rows": rows,
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    print("\n汇总:", json.dumps(summary, ensure_ascii=False))
    print(f"[OK] 明细写入 {out}")
    return 0


