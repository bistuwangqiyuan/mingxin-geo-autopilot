def _load_client() -> dict:
    if not CLIENT_FILE.exists():
        sys.exit(f"[!] Missing {CLIENT_FILE}.\n    Run: python gsc_cli.py setup-help")
    raw = json.loads(CLIENT_FILE.read_text(encoding="utf-8"))
    node = raw.get("installed") or raw.get("web") or raw
    cid, csec = node.get("client_id"), node.get("client_secret")
    if not cid or not csec:
        sys.exit(f"[!] {CLIENT_FILE} has no client_id/client_secret. Re-download the OAuth Desktop client.")
    return {"client_id": cid, "client_secret": csec}


def _save_token(tok: dict) -> None:
    SECRETS.mkdir(parents=True, exist_ok=True)
    TOKEN_FILE.write_text(json.dumps(tok, ensure_ascii=False, indent=2), encoding="utf-8")


def _access_token() -> str:
    """Return a valid access token, refreshing via the cached refresh token."""
    if not TOKEN_FILE.exists():
        sys.exit("[!] Not authorized yet. Run: python gsc_cli.py auth")
    tok = json.loads(TOKEN_FILE.read_text(encoding="utf-8"))
    # reuse cached access token if still valid (60s safety margin)
    exp = tok.get("expires_at", 0)
    if tok.get("access_token") and exp - 60 > time.time():
        return tok["access_token"]
    cl = _load_client()
    st, data = _post_form(TOKEN_ENDPOINT, {
        "client_id": cl["client_id"],
        "client_secret": cl["client_secret"],
        "refresh_token": tok["refresh_token"],
        "grant_type": "refresh_token",
    })
    if st != 200 or "access_token" not in data:
        sys.exit(f"[!] Token refresh failed ({st}): {data}\n    Re-run: python gsc_cli.py auth")
    tok["access_token"] = data["access_token"]
    tok["expires_at"] = time.time() + int(data.get("expires_in", 3600))
    _save_token(tok)
    return tok["access_token"]


class _CodeHandler(http.server.BaseHTTPRequestHandler):
    code: str | None = None
    state: str | None = None

    def do_GET(self):  # noqa: N802
        q = urllib.parse.urlparse(self.path).query
        params = urllib.parse.parse_qs(q)
        _CodeHandler.code = (params.get("code") or [None])[0]
        _CodeHandler.state = (params.get("state") or [None])[0]
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.end_headers()
        ok = bool(_CodeHandler.code)
        msg = ("授权成功，可以关闭此页面并回到 Cursor。" if ok
               else "未收到授权码，请重试。")
        self.wfile.write(f"<html><body style='font-family:sans-serif;padding:40px'>"
                         f"<h2>{'✅' if ok else '⚠️'} {msg}</h2></body></html>".encode())

    def log_message(self, *_):  # silence
        return


def cmd_auth(_args) -> int:
    cl = _load_client()
    state = _secrets.token_urlsafe(16)
    # bind a loopback port
    server = http.server.HTTPServer(("127.0.0.1", 0), _CodeHandler)
    port = server.server_address[1]
    redirect_uri = f"http://127.0.0.1:{port}/"
    auth_url = AUTH_ENDPOINT + "?" + urllib.parse.urlencode({
        "client_id": cl["client_id"],
        "redirect_uri": redirect_uri,
        "response_type": "code",
        "scope": SCOPE,
        "access_type": "offline",
        "prompt": "consent",
        "state": state,
    })
    print("\n=== 一次性授权 ===")
    print("1) 在浏览器打开下面这个链接并用 mingxinstorage.xyz 的 GSC 账号同意授权：\n")
    print(auth_url + "\n")
    print(f"   (本地回调端口: {port}；授权后会自动跳回并被本工具捕获)")
    try:
        webbrowser.open(auth_url)
    except Exception:  # noqa: BLE001
        pass

    th = threading.Thread(target=server.handle_request, daemon=True)
    th.start()
    print("\n等待授权回调中（最多 300 秒）...")
    th.join(timeout=300)
    server.server_close()

    if not _CodeHandler.code:
        sys.exit("[!] 未捕获到授权码（超时或被拒绝）。请重试 auth。")
    if _CodeHandler.state != state:
        sys.exit("[!] state 校验失败，已中止（防 CSRF）。请重试 auth。")

    st, data = _post_form(TOKEN_ENDPOINT, {
        "client_id": cl["client_id"],
        "client_secret": cl["client_secret"],
        "code": _CodeHandler.code,
        "grant_type": "authorization_code",
        "redirect_uri": redirect_uri,
    })
    if st != 200 or "refresh_token" not in data:
        sys.exit(f"[!] 兑换令牌失败 ({st}): {data}\n"
                 f"    提示：若没有 refresh_token，请到账号的“第三方访问权限”移除旧授权后重试 auth。")
    tok = {
        "refresh_token": data["refresh_token"],
        "access_token": data.get("access_token"),
        "expires_at": time.time() + int(data.get("expires_in", 3600)),
        "scope": data.get("scope", SCOPE),
        "authorized_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
    }
    _save_token(tok)
    print(f"\n[OK] 授权完成，已缓存刷新令牌到 {TOKEN_FILE}")
    print("     之后所有命令都无需再次登录（除非你主动撤销授权）。")
    return 0


